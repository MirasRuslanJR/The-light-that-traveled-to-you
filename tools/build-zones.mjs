// Builds js/data/zones.js: coordinates of every IANA time zone's principal city, plus legacy aliases.
// Source: IANA tz database (public domain), files zone.tab and backward.
// Usage: node tools/build-zones.mjs path/to/zone.tab path/to/backward
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [zoneTab, backward] = process.argv.slice(2);
const toDeg = (s, degDigits) => {
  const sign = s[0] === '-' ? -1 : 1;
  const d = +s.slice(1, 1 + degDigits), m = +s.slice(1 + degDigits, 3 + degDigits), sec = +(s.slice(3 + degDigits, 5 + degDigits) || 0);
  return Math.round(sign * (d + m / 60 + sec / 3600) * 100) / 100;
};
const zones = {};
for (const line of readFileSync(zoneTab, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coord, tz] = line.split('\t');
  const m = /^([+-]\d+)([+-]\d+)$/.exec(coord);
  const lat = toDeg(m[1], 2), lon = toDeg(m[2], 3);
  zones[tz] = [lat, lon];
}
let aliases = 0;
for (const line of readFileSync(backward, 'utf8').split('\n')) {
  const m = /^Link\s+(\S+)\s+(\S+)/.exec(line);
  if (m && zones[m[1]] && !zones[m[2]]) { zones[m[2]] = zones[m[1]]; aliases++; }
}
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'js', 'data', 'zones.js'),
  `// Generated by tools/build-zones.mjs from the IANA tz database (public domain). [lat, lon east-positive]\nexport const ZONES = ${JSON.stringify(zones)};\n`);
console.log(`zones: ${Object.keys(zones).length} (incl. ${aliases} legacy aliases)`);
