// Usage: node tools/build-lines.mjs path/to/constellations.lines.json
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const geo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const vec = ([lon, lat]) => {
  const ra = ((lon % 360) + 360) % 360 * Math.PI / 180, dec = lat * Math.PI / 180;
  return [Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec)].map((v) => Math.round(v * 1e4) / 1e4);
};
const out = [];
let segments = 0;
for (const f of geo.features) {
  for (const line of f.geometry.coordinates) {
    for (let k = 0; k + 1 < line.length; k++) { out.push(...vec(line[k]), ...vec(line[k + 1])); segments++; }
  }
}
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'js', 'data', 'lines.js'),
`// Generated by tools/build-lines.mjs. Constellation lines from d3-celestial,
// Copyright (c) 2015, Olaf Frohn. BSD 3-Clause licence (see docs/LICENSES.md).
// Flat list of segment endpoints: [x1, y1, z1, x2, y2, z2, ...], J2000 equatorial unit vectors.
export const LINES = [${out.join(',')}];
`);
console.log(`constellations: ${geo.features.length}, segments: ${segments}`);
